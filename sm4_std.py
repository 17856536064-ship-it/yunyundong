def _rotl(x: int, n: int) -> int:
    return ((x << n) | (x >> (32 - n))) & 0xFFFFFFFF


def _tau(a: int) -> int:
    return (
        (SBOX[(a >> 24) & 0xFF] << 24)
        | (SBOX[(a >> 16) & 0xFF] << 16)
        | (SBOX[(a >> 8) & 0xFF] << 8)
        | SBOX[a & 0xFF]
    )


def _l_enc(b: int) -> int:
    # L(B) = B xor (B<<<2) xor (B<<<10) xor (B<<<18) xor (B<<<24)
    return b ^ _rotl(b, 2) ^ _rotl(b, 10) ^ _rotl(b, 18) ^ _rotl(b, 24)


def _l_key(b: int) -> int:
    # L'(B) = B xor (B<<<13) xor (B<<<23)   —— 仅两项，不能多
    return b ^ _rotl(b, 13) ^ _rotl(b, 23)


def _t_enc(x: int) -> int:
    return _l_enc(_tau(x))


def _t_key(x: int) -> int:
    return _l_key(_tau(x))


def expand_key(key16: bytes) -> list[int]:
    assert len(key16) == 16
    mk = [int.from_bytes(key16[i : i + 4], "big") for i in range(0, 16, 4)]
    k = [mk[i] ^ FK[i] for i in range(4)]
    rk = []
    for i in range(32):
        # rk[i] = K[i] ⊕ T'(K[i+1]⊕K[i+2]⊕K[i+3]⊕CK[i])，不是 k[(i+1)%4]
        tmp = k[i] ^ _t_key(k[i + 1] ^ k[i + 2] ^ k[i + 3] ^ CK[i])
        k.append(tmp)
        rk.append(tmp)
    return rk


def crypt_block(rk: list[int], block: bytes, decrypt: bool = False) -> bytes:
    assert len(block) == 16
    x = [int.from_bytes(block[i : i + 4], "big") for i in range(0, 16, 4)]
    order = rk[::-1] if decrypt else rk
    for i in range(32):
        x.append(x[i] ^ _t_enc(x[i + 1] ^ x[i + 2] ^ x[i + 3] ^ order[i]))
    return b"".join(x[35 - j].to_bytes(4, "big") for j in range(4))


def pkcs7_pad(data: bytes) -> bytes:
    n = 16 - (len(data) % 16)
    return data + bytes([n]) * n


def pkcs7_unpad(data: bytes) -> bytes:
    if not data:
        return data
    n = data[-1]
    if 1 <= n <= 16 and data[-n:] == bytes([n]) * n:
        return data[:-n]
    return data


def ecb_encrypt(key16: bytes, data: bytes) -> bytes:
    rk = expand_key(key16)
    data = pkcs7_pad(data)
    return b"".join(crypt_block(rk, data[i : i + 16]) for i in range(0, len(data), 16))


def ecb_decrypt(key16: bytes, data: bytes) -> bytes:
    rk = expand_key(key16)
    pt = b"".join(crypt_block(rk, data[i : i + 16], True) for i in range(0, len(data), 16))
    return pkcs7_unpad(pt)


def cbc_decrypt(key16: bytes, data: bytes, iv: bytes = b"\x00" * 16) -> bytes:
    rk = expand_key(key16)
    out, prev = b"", iv
    for i in range(0, len(data), 16):
        blk = crypt_block(rk, data[i : i + 16], True)
        out += bytes(a ^ b for a, b in zip(blk, prev))
        prev = data[i : i + 16]
    return pkcs7_unpad(out)


def selftest() -> None:
    k = bytes.fromhex("0123456789abcdeffedcba9876543210")
    p = bytes.fromhex("0123456789abcdeffedcba9876543210")
    expect = bytes.fromhex("681edf34d206965e86b3e94f536e4246")
    got = crypt_block(expand_key(k), p)
    assert got == expect, f"SM4 testvector FAIL got={got.hex()}"
    assert ecb_decrypt(k, ecb_encrypt(k, b'{"type":"1"}')) == b'{"type":"1"}'
    print("SM4 selftest OK")


if __name__ == "__main__":
    selftest()
